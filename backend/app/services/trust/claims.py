"""Claim models and verdict schemas for Proof-Carrying Contributions.

IMPORTANT: Proposers (LLM / user / tools) create Claims without verdict fields.
Only the deterministic Kernel can issue Verdicts.
"""

from enum import Enum
import hashlib
import hmac
from typing import Any, Dict, List, Optional
from uuid import uuid4
from pydantic import BaseModel, ConfigDict, Field

KERNEL_SECRET_DEFAULT = "firstpatch_kernel_internal_seal_v1"


def compute_verdict_seal(
    claim_id: str,
    status: str,
    snapshot_sha: str,
    reason_code: str,
    secret: str = KERNEL_SECRET_DEFAULT,
) -> str:
    """Computes an HMAC-SHA256 seal authenticating that a verdict was issued by the Kernel."""
    payload = f"{claim_id}:{status}:{snapshot_sha}:{reason_code}"
    return hmac.new(secret.encode("utf-8"), payload.encode("utf-8"), hashlib.sha256).hexdigest()


class ClaimType(str, Enum):
    FILE_EXISTS = "FILE_EXISTS"
    SYMBOL_IN_FILE = "SYMBOL_IN_FILE"
    LINES_CONTAIN = "LINES_CONTAIN"
    IMPORTED_BY = "IMPORTED_BY"
    TEST_IMPORTS = "TEST_IMPORTS"
    POLICY_FACT = "POLICY_FACT"
    ISSUE_UNCLAIMED = "ISSUE_UNCLAIMED"
    VERIFY_RESULT = "VERIFY_RESULT"
    REVIEW_THEME_SUPPORTED = "REVIEW_THEME_SUPPORTED"


class VerdictStatus(str, Enum):
    VERIFIED = "VERIFIED"
    REFUTED = "REFUTED"
    STALE = "STALE"
    UNKNOWN = "UNKNOWN"


class Claim(BaseModel):
    """An untrusted structured assertion generated by an LLM or static proposer.
    
    Notice there is strictly NO 'is_verified' or 'verdict' field on this model.
    Proposers cannot self-certify assertions. Extra fields are strictly forbidden.
    """
    model_config = ConfigDict(extra="forbid")

    claim_id: str = Field(default_factory=lambda: str(uuid4()))
    claim_type: ClaimType
    arguments: Dict[str, Any] = Field(default_factory=dict)
    repository: str
    snapshot_sha: str
    evidence_refs: List[str] = Field(default_factory=list)
    stance: str = "asserts"


class Verdict(BaseModel):
    """Deterministic verdict generated exclusively by the Kernel."""
    claim_id: str
    status: VerdictStatus
    snapshot_sha: str
    reason_code: str
    explanation: str
    witness: Optional[Dict[str, Any]] = None
    kernel_seal: Optional[str] = None

    def is_sealed_by_kernel(self, secret: str = KERNEL_SECRET_DEFAULT) -> bool:
        """Verifies whether this verdict carries a genuine kernel authentication seal."""
        if not self.kernel_seal:
            return False
        expected = compute_verdict_seal(
            self.claim_id,
            self.status.value if isinstance(self.status, VerdictStatus) else str(self.status),
            self.snapshot_sha,
            self.reason_code,
            secret,
        )
        return hmac.compare_digest(self.kernel_seal, expected)

