"""Claim models and verdict schemas for Proof-Carrying Contributions.

IMPORTANT: Proposers (LLM / user / tools) create Claims without verdict fields.
Only the deterministic Kernel can issue Verdicts.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4
from pydantic import BaseModel, Field


class ClaimType(str, Enum):
    FILE_EXISTS = "FILE_EXISTS"
    SYMBOL_IN_FILE = "SYMBOL_IN_FILE"
    LINES_CONTAIN = "LINES_CONTAIN"
    IMPORTED_BY = "IMPORTED_BY"
    TEST_IMPORTS = "TEST_IMPORTS"
    POLICY_FACT = "POLICY_FACT"
    ISSUE_UNCLAIMED = "ISSUE_UNCLAIMED"
    VERIFY_RESULT = "VERIFY_RESULT"
    REVIEW_THEME_SUPPORTED = "REVIEW_THEME_SUPPORTED"


class VerdictStatus(str, Enum):
    VERIFIED = "VERIFIED"
    REFUTED = "REFUTED"
    STALE = "STALE"
    UNKNOWN = "UNKNOWN"


class Claim(BaseModel):
    """An untrusted structured assertion generated by an LLM or static proposer.
    
    Notice there is strictly NO 'is_verified' or 'verdict' field on this model.
    Proposers cannot self-certify assertions.
    """
    claim_id: str = Field(default_factory=lambda: str(uuid4()))
    claim_type: ClaimType
    arguments: Dict[str, Any] = Field(default_factory=dict)
    repository: str
    snapshot_sha: str
    evidence_refs: List[str] = Field(default_factory=list)
    stance: str = "asserts"


class Verdict(BaseModel):
    """Deterministic verdict generated exclusively by the Kernel."""
    claim_id: str
    status: VerdictStatus
    snapshot_sha: str
    reason_code: str
    explanation: str
    witness: Optional[Dict[str, Any]] = None
