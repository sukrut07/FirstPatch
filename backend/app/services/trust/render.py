"""Trusted Renderer for Proof-Carrying Contributions.

Renders verified statements from templates and kernel-validated witnesses.
Model-generated explanatory prose is strictly separated into an 'unverified explanation'
section. Refuted claims are removed from actionable steps and relegated to diagnostics.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from app.services.trust.claims import Claim, ClaimType, Verdict, VerdictStatus


class PlanStep(BaseModel):
    step_id: int
    action: str
    grounded_statement: str
    claim_ids: List[str] = Field(default_factory=list)
    status: str  # "verified", "unresolved", "rejected"
    witnesses: List[Dict[str, Any]] = Field(default_factory=list)


class RenderedContributionPackage(BaseModel):
    repository: str
    snapshot_sha: str
    verified_steps: List[PlanStep] = Field(default_factory=list)
    unresolved_steps: List[PlanStep] = Field(default_factory=list)
    rejected_claims_diagnostic: List[Dict[str, Any]] = Field(default_factory=list)
    unverified_explanation: Optional[str] = None
    summary_markdown: str


class TrustedRenderer:
    def __init__(self):
        pass

    def render_plan(
        self,
        repository: str,
        snapshot_sha: str,
        claims: List[Claim],
        verdicts: List[Verdict],
        raw_model_explanation: Optional[str] = None,
    ) -> RenderedContributionPackage:
        verdict_by_id = {v.claim_id: v for v in verdicts}
        verified_steps: List[PlanStep] = []
        unresolved_steps: List[PlanStep] = []
        rejected_diagnostics: List[Dict[str, Any]] = []

        step_counter = 1

        for claim in claims:
            v = verdict_by_id.get(claim.claim_id)
            if not v:
                continue

            if v.status == VerdictStatus.VERIFIED:
                statement = self._format_verified_statement(claim, v)
                verified_steps.append(
                    PlanStep(
                        step_id=step_counter,
                        action=claim.claim_type.value,
                        grounded_statement=statement,
                        claim_ids=[claim.claim_id],
                        status="verified",
                        witnesses=[v.witness] if v.witness else [],
                    )
                )
                step_counter += 1

            elif v.status in (VerdictStatus.STALE, VerdictStatus.UNKNOWN):
                statement = f"Unresolved claim ({v.status.value}): {claim.claim_type.value} - {v.explanation}"
                unresolved_steps.append(
                    PlanStep(
                        step_id=step_counter,
                        action=claim.claim_type.value,
                        grounded_statement=statement,
                        claim_ids=[claim.claim_id],
                        status="unresolved",
                        witnesses=[],
                    )
                )
                step_counter += 1

            elif v.status == VerdictStatus.REFUTED:
                rejected_diagnostics.append(
                    {
                        "claim_id": claim.claim_id,
                        "type": claim.claim_type.value,
                        "arguments": claim.arguments,
                        "reason_code": v.reason_code,
                        "explanation": v.explanation,
                    }
                )

        # Generate summary markdown
        lines = [
            f"# Contribution Plan for {repository} (`{snapshot_sha[:8]}`)",
            "",
            "## 1. Verified Implementation Steps",
        ]

        if verified_steps:
            for s in verified_steps:
                lines.append(f"- **Step {s.step_id}**: {s.grounded_statement}")
        else:
            lines.append("_No verified steps available._")

        lines.append("")
        lines.append("## 2. Unresolved or Stale Items")
        if unresolved_steps:
            for u in unresolved_steps:
                lines.append(f"- **[?] Step {u.step_id}**: {u.grounded_statement}")
        else:
            lines.append("_None._")

        lines.append("")
        lines.append("## 3. Rejected Claim Diagnostics (Refuted by Kernel)")
        if rejected_diagnostics:
            for r in rejected_diagnostics:
                lines.append(f"- **Rejected** `{r['type']}`: {r['explanation']} (Reason: `{r['reason_code']}`)")
        else:
            lines.append("_No claims were refuted._")

        if raw_model_explanation:
            lines.append("")
            lines.append("## 4. Unverified Model Explanation (Untrusted Proposer Output)")
            lines.append("> ⚠️ **Notice**: The following text is generated by an untrusted AI model and has NOT been certified by the deterministic kernel.")
            lines.append("")
            for pline in raw_model_explanation.strip().splitlines():
                lines.append(f"> {pline}")

        summary_md = "\n".join(lines)

        return RenderedContributionPackage(
            repository=repository,
            snapshot_sha=snapshot_sha,
            verified_steps=verified_steps,
            unresolved_steps=unresolved_steps,
            rejected_claims_diagnostic=rejected_diagnostics,
            unverified_explanation=raw_model_explanation,
            summary_markdown=summary_md,
        )

    def _format_verified_statement(self, claim: Claim, verdict: Verdict) -> str:
        args = claim.arguments
        witness = verdict.witness or {}

        if claim.claim_type == ClaimType.FILE_EXISTS:
            p = witness.get("path", args.get("path", "file"))
            return f"Inspect repository file `{p}`."

        if claim.claim_type == ClaimType.SYMBOL_IN_FILE:
            p = witness.get("path", args.get("path", "file"))
            sym = witness.get("symbol_name", args.get("symbol_name", "symbol"))
            start = witness.get("start_line")
            end = witness.get("end_line")
            if start and end:
                return f"Inspect `{p}`, symbol `{sym}`, lines {start}–{end}."
            return f"Inspect `{p}`, symbol `{sym}`."

        if claim.claim_type == ClaimType.LINES_CONTAIN:
            p = witness.get("path", args.get("path", "file"))
            return f"Verify logic in `{p}` matching verified lines."

        if claim.claim_type == ClaimType.IMPORTED_BY:
            src = witness.get("source_path", args.get("source_path"))
            mod = witness.get("imported_module", args.get("imported_module"))
            return f"Check dependent interface in `{src}` importing `{mod}`."

        if claim.claim_type == ClaimType.TEST_IMPORTS:
            t = witness.get("test_path", args.get("test_path"))
            target = witness.get("target_module", args.get("target_module"))
            return f"Run and update test suite `{t}` exercising `{target}`."

        if claim.claim_type == ClaimType.POLICY_FACT:
            pt = witness.get("policy_type", args.get("policy_type"))
            val = witness.get("value", args.get("value"))
            return f"Adhere to verified policy `{pt}`: `{val}`."

        if claim.claim_type == ClaimType.ISSUE_UNCLAIMED:
            num = witness.get("issue_number", args.get("issue_number"))
            return f"Proceed with issue #{num} (confirmed open, unassigned, and unclaimed)."

        if claim.claim_type == ClaimType.VERIFY_RESULT:
            driver = witness.get("driver", "isolated driver")
            return f"Verified test execution passed under `{driver}`."

        if claim.claim_type == ClaimType.REVIEW_THEME_SUPPORTED:
            theme = witness.get("theme", args.get("theme"))
            count = witness.get("comment_count", 2)
            return f"Apply historical reviewer guidance on theme '{theme}' (supported by {count} PR comments)."

        return f"Execute verified action for {claim.claim_type.value}."
